const LANGUAGE_OPTIONS = [
    { code: 'zh', label: '中文' },
    { code: 'en', label: 'English' },
    { code: 'fr', label: 'Français' },
    { code: 'es', label: 'Español' },
    { code: 'ja', label: '日本語' },
    { code: 'ko', label: '한국어' }
];

function getCurrentLanguage() {
    return localStorage.getItem('siteLanguage') || 'zh';
}

function translateText(text, lang = getCurrentLanguage()) {
    if (lang === 'zh') return text;
    return I18N_DICTIONARY[lang]?.[text] || text;
}

function rememberOriginalText(element) {
    const text = element.textContent.trim();
    if (text && !element.dataset.i18nOriginalText && element.children.length === 0) {
        element.dataset.i18nOriginalText = text;
    }
}

function rememberOriginalPlaceholder(element) {
    const placeholder = element.getAttribute('placeholder');
    if (placeholder && !element.dataset.i18nOriginalPlaceholder) {
        element.dataset.i18nOriginalPlaceholder = placeholder;
    }
}

function applyTranslations() {
    const lang = getCurrentLanguage();
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;

    document.querySelectorAll('h1, h2, h3, h4, label, button, a, p, th, option, span').forEach(element => {
        if (element.closest('.language-switcher')) return;
        rememberOriginalText(element);
        const original = element.dataset.i18nOriginalText;
        if (original) element.textContent = translateText(original, lang);
    });

    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(element => {
        rememberOriginalPlaceholder(element);
        const original = element.dataset.i18nOriginalPlaceholder;
        if (original) element.setAttribute('placeholder', translateText(original, lang));
    });

    if (!document.body.dataset.i18nOriginalTitle) {
        document.body.dataset.i18nOriginalTitle = document.title;
    }
    document.title = translateText(document.body.dataset.i18nOriginalTitle, lang);
}

function createLanguageSwitcher() {
    if (document.getElementById('languageSelect')) return;

    const wrapper = document.createElement('div');
    wrapper.className = 'language-switcher';

    const label = document.createElement('label');
    label.setAttribute('for', 'languageSelect');
    label.textContent = translateText('语言', getCurrentLanguage());

    const select = document.createElement('select');
    select.id = 'languageSelect';
    select.innerHTML = LANGUAGE_OPTIONS.map(option => `<option value="${option.code}">${option.label}</option>`).join('');
    select.value = getCurrentLanguage();
    select.addEventListener('change', () => {
        localStorage.setItem('siteLanguage', select.value);
        applyTranslations();
        label.textContent = translateText('语言', select.value);
    });

    wrapper.appendChild(label);
    wrapper.appendChild(select);

    const navLinks = document.querySelector('.nav-links');
    if (navLinks) {
        navLinks.appendChild(wrapper);
    } else {
        document.body.insertBefore(wrapper, document.body.firstChild);
    }
}

window.applyTranslations = applyTranslations;
window.translateText = translateText;

document.addEventListener('DOMContentLoaded', () => {
    createLanguageSwitcher();
    applyTranslations();
});
